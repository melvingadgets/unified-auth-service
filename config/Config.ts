import dotenv from "dotenv";

dotenv.config();

const portValue = String(process.env.PORT ?? "5500").trim();
const databaseUrl = String(process.env.DATABASE_URL ?? process.env.Database_url ?? "").trim();
const jwtSecret = String(process.env.AUTH_JWT_SECRET ?? process.env.JWT_SECRET ?? "").trim();
const serviceKey = String(process.env.AUTH_SERVICE_KEY ?? "").trim();
const publicBaseUrl = String(process.env.AUTH_SERVICE_PUBLIC_URL ?? `http://localhost:${portValue}`).trim();
const corsOrigins = String(process.env.CORS_ORIGINS ?? "").trim();
const googleClientId = String(process.env.GOOGLE_CLIENT_ID ?? "").trim();
const mailFrom = String(process.env.MAIL_FROM ?? "").trim();
const mailProviderRaw = String(process.env.MAIL_PROVIDER ?? "smtp").trim().toLowerCase();
const mailProvider = mailProviderRaw === "resend" ? "resend" : "smtp";
const gmailUser = String(process.env.GMAIL_USER ?? "").trim();
const gmailAppPassword = String(process.env.GMAIL_APP_PASSWORD ?? "").trim();
const resendApiKey = String(process.env.RESEND_API_KEY ?? "").trim();

// RS256 signing keys (Shortwork/AGENTS.md §2.3): base64 of a JSON array of
// { kid, privateKeyPem }, generated by scripts/signing-keys.ts. Every listed key
// is published in the JWKS; AUTH_ACTIVE_KID picks the one new tokens use.
// Unset keeps the service on legacy HS256 tokens only (additive rollout, §7.1).
type SigningKeyConfig = { kid: string; privateKeyPem: string };
const parseSigningKeys = (raw: string): SigningKeyConfig[] => {
  if (!raw) return [];
  try {
    const parsed = JSON.parse(Buffer.from(raw, "base64").toString("utf8")) as unknown;
    if (
      Array.isArray(parsed) &&
      parsed.every((key) => typeof key?.kid === "string" && typeof key?.privateKeyPem === "string")
    ) {
      return parsed as SigningKeyConfig[];
    }
  } catch {
    // fall through to the error below
  }
  throw new Error("AUTH_SIGNING_KEYS_B64 must be base64 of a JSON array of { kid, privateKeyPem }");
};
const signingKeys = parseSigningKeys(String(process.env.AUTH_SIGNING_KEYS_B64 ?? "").trim());

// OAuth clients (one per backend): base64 of a JSON array of { clientId, service, secretHash },
// written by scripts/oauth-clients.ts. Only sha256 hashes live here; each backend holds its own
// plaintext secret. What a client may request comes from GRANTS in the platform kit.
type OAuthClientConfig = { clientId: string; service: string; secretHash: string };
const parseOAuthClients = (raw: string): OAuthClientConfig[] => {
  if (!raw) return [];
  let parsed: unknown;
  try {
    parsed = JSON.parse(Buffer.from(raw, "base64").toString("utf8"));
  } catch {
    throw new Error("AUTH_OAUTH_CLIENTS_B64 must be base64 of a JSON array");
  }
  const valid =
    Array.isArray(parsed) &&
    parsed.every(
      (client) =>
        typeof client?.clientId === "string" &&
        typeof client?.service === "string" &&
        typeof client?.secretHash === "string" &&
        /^[0-9a-f]{64}$/.test(client.secretHash)
    );
  if (!valid) throw new Error("AUTH_OAUTH_CLIENTS_B64 entries need clientId, service and a sha256 hex secretHash");
  const clients = parsed as OAuthClientConfig[];
  if (new Set(clients.map((client) => client.clientId)).size !== clients.length) {
    throw new Error("AUTH_OAUTH_CLIENTS_B64 has duplicate clientIds");
  }
  return clients;
};
const oauthClients = parseOAuthClients(String(process.env.AUTH_OAUTH_CLIENTS_B64 ?? "").trim());
const activeKid = String(process.env.AUTH_ACTIVE_KID ?? signingKeys[signingKeys.length - 1]?.kid ?? "").trim();
const refreshTokenTtlDays = Number(process.env.AUTH_REFRESH_TOKEN_TTL_DAYS ?? 30) || 30;

const missing: string[] = [];
if (!databaseUrl) missing.push("DATABASE_URL");
if (!jwtSecret) missing.push("AUTH_JWT_SECRET (or JWT_SECRET)");

if (missing.length > 0) {
  throw new Error(`Missing required environment variables: ${missing.join(", ")}`);
}

export const config = {
  port: Number(portValue) || 5500,
  databaseUrl,
  jwtSecret,
  serviceKey,
  publicBaseUrl,
  corsOrigins: corsOrigins
    ? corsOrigins.split(",").map((origin) => origin.trim()).filter(Boolean)
    : [],
  googleClientId,
  // `iss` of every RS256 token; receivers compare it exactly.
  issuer: publicBaseUrl.replace(/\/+$/, ""),
  signingKeys,
  activeKid,
  refreshTokenTtlDays,
  oauthClients,
  mail: {
    provider: mailProvider,
    from: mailFrom,
    smtp: {
      gmailUser,
      gmailAppPassword,
    },
    resend: {
      apiKey: resendApiKey,
    },
  },
};
